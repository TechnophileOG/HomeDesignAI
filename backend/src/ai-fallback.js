/* ════════════════════════════════════════════════════════════════════════
   KatalogitAI — Vertex AI managed-API fallback (image generation)
   ────────────────────────────────────────────────────────────────────────
   When the GPU box isn't configured (quota pending) or a GPU submit fails,
   jobs render through Google's managed image model — the cheapest ACTIVE
   lane: `gemini-3.1-flash-lite-image` (Nano Banana 2 Lite, ~$0.034 per 1K
   image). No GPU bill, no self-hosting. The model is env-configurable.

   Same contract as submitGpuJob(): returns { poses: [{poseId, index,
   objectPath}] } so jobs.js persists the gallery identically regardless of
   which engine produced it. Output paths are BYTE-IDENTICAL to the GPU
   path (same store/product/pose seed), so switching engines never orphans
   or duplicates a gallery.

   Cost honesty: the ₹1–3/SKU target is only reachable on the self-hosted
   GPU pipeline; this fallback keeps the product testable meanwhile. Batch
   inference (Vertex BatchPredictionJob, ~50% off) is the next cost lever.
   ════════════════════════════════════════════════════════════════════════ */

import { Storage } from '@google-cloud/storage';
import { GoogleAuth } from 'google-auth-library';
import {
  PROJECT_ID, VERTEX_AI_LOCATION, VERTEX_AI_MODEL,
  GCS_ORIGINALS_BUCKET, GCS_PROCESSED_BUCKET,
} from './config.js';
import { buildPrompt, POSE_LIST, fnv1a } from './ai-client.js';
import { AppError } from './errors.js';

const storage = new Storage();
const auth = new GoogleAuth({ scopes: ['https://www.googleapis.com/auth/cloud-platform'] });

// Pose frame — portrait 2:3, matches the GPU pipeline (512×768 → ~1K here).
const ASPECT_RATIO = '2:3';

/** Vertex generateContent endpoint for the configured model. Pure (testable). */
export const vertexEndpoint = ({
  project = PROJECT_ID,
  location = VERTEX_AI_LOCATION,
  model = VERTEX_AI_MODEL,
} = {}) => {
  const base = location === 'global'
    ? 'https://aiplatform.googleapis.com'
    : `https://${location}-aiplatform.googleapis.com`;
  return `${base}/v1/projects/${project}/locations/${location}/publishers/google/models/${model}:generateContent`;
};

/** Per-pose prompt: sanitized garment descriptor + the pose instruction. */
export const posePrompt = (product, pose) =>
  `${buildPrompt(product)}, ${pose.prompt}`.trim();

/** Deterministic output path — SAME naming as the GPU path (shared seed). */
export const fallbackOutputPath = ({ storeId, productId, index, seed }) =>
  `stores/${storeId}/products/${productId}/poses/pose_${index}_${seed}.png`;

/** One generateContent call → PNG bytes. Error mapping keeps job state sane. */
async function generateOne({ prompt, flatLayGcsUri, flatLayMimeType }) {
  const token = await auth.getAccessToken();
  if (!token) {
    throw new AppError(502, 'VERTEX_AUTH_FAILED', 'Vertex AI authentication failed.');
  }
  let res;
  try {
    res = await fetch(vertexEndpoint(), {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
      body: JSON.stringify({
        contents: [{
          role: 'user',
          parts: [
            { fileData: { mimeType: flatLayMimeType, fileUri: flatLayGcsUri } },
            { text: prompt },
          ],
        }],
        generationConfig: { temperature: 1.0, responseModalities: ['IMAGE'] },
        imageConfig: { aspectRatio: ASPECT_RATIO },
      }),
      signal: AbortSignal.timeout(120_000),
    });
  } catch {
    throw new AppError(502, 'VERTEX_UNREACHABLE', 'Vertex AI is unreachable.');
  }
  if (!res.ok) {
    const text = await res.text().catch(() => '');
    if (res.status === 403) {
      throw new AppError(502, 'VERTEX_FORBIDDEN',
        'Vertex AI access denied — grant the runtime service account roles/aiplatform.user.');
    }
    if (res.status === 429) {
      throw new AppError(502, 'VERTEX_QUOTA', 'Vertex AI quota exceeded — try again shortly.');
    }
    console.error('[ai-fallback] vertex error:', res.status, text.slice(0, 300));
    throw new AppError(502, 'VERTEX_FAILED', 'Vertex AI generation failed.');
  }
  const body = await res.json().catch(() => ({}));
  const parts = body?.candidates?.[0]?.content?.parts || [];
  const img = parts.find((p) => p.inlineData?.data);
  if (!img) {
    throw new AppError(502, 'VERTEX_NO_IMAGE', 'Vertex AI returned no image.');
  }
  return Buffer.from(img.inlineData.data, 'base64');
}

/** Upload generated bytes to the processed bucket (server-side, SA creds). */
export async function uploadGenerated(bucketName, objectPath, buffer, contentType = 'image/png') {
  await storage.bucket(bucketName).file(objectPath).save(buffer, { contentType, resumable: false });
  return objectPath;
}

/** Small concurrency map (no dependency): keeps ~3 calls in flight to Vertex
    so an 8-pose SKU completes in ~3 rounds instead of 8 sequential waits. */
async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i], i);
    }
  };
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return out;
}

/**
 * Render every pose through Vertex AI. `deps.generate`/`deps.upload` are
 * injectable for tests. Returns the same shape as submitGpuJob().
 */
export async function generateWithVertexAi(
  { job, product },
  { generate = generateOne, upload = uploadGenerated } = {},
) {
  const flatLayPath = product.flatLay?.path;
  if (!flatLayPath) throw new AppError(400, 'INVALID_FIELD', 'Product has no flat-lay photo.');
  const flatLayGcsUri = `gs://${GCS_ORIGINALS_BUCKET}/${flatLayPath}`;
  const flatLayMimeType = /^image\//.test(product.flatLay?.contentType || '')
    ? product.flatLay.contentType
    : 'image/png';
  const seedBase = `${job.storeId}:${product.id}`;

  const rendered = await mapLimit(POSE_LIST, 3, async (pose) => {
    const seed = fnv1a(`${seedBase}:${pose.id}`);
    const png = await generate({ prompt: posePrompt(product, pose), flatLayGcsUri, flatLayMimeType });
    const objectPath = fallbackOutputPath({
      storeId: job.storeId, productId: product.id, index: pose.index, seed,
    });
    await upload(GCS_PROCESSED_BUCKET, objectPath, png);
    return { poseId: pose.id, index: pose.index, objectPath };
  });

  return { poses: rendered };
}
